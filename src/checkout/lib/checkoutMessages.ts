export const getCheckoutLocale = (locale?: string): CheckoutLocale => (locale === "ar" ? "ar" : "en");

export const getCheckoutLocaleTag = (locale?: string) =>
	getCheckoutLocale(locale) === "ar" ? "ar-AE" : "en-US";

export const getCheckoutLanguageCode = (locale?: string) =>
	getCheckoutLocale(locale) === "ar" ? "AR_AE" : "EN_US";

export const getCheckoutMessages = (locale?: string) => checkoutMessages[getCheckoutLocale(locale)];

export const useCheckoutMessages = () => {
	const locale = useLocale();

	return {
		locale: getCheckoutLocale(locale),
		...getCheckoutMessages(locale),
	};
};
